func TestInspectQUICSNIAndFallback(t *testing.T) {
	t.Parallel()
	filter, err := filtering.New(&filtering.Config{Logger: slogutil.NewDiscardLogger(), ProtectionEnabled: true}, []filtering.Filter{{ID: 1, Data: []byte("||blocked.test^")}})
	require.NoError(t, err)
	filter.SetEnabled(true)
	f := &Filter{logger: slogutil.NewDiscardLogger(), filter: filter, inspectQUIC: true, quicPorts: []uint16{443}, flows: map[flowKey]*flow{}}
	makePacket := func(host string, port uint16) *packet {
		return &packet{src: netip.AddrPortFrom(netip.MustParseAddr("127.0.0.1"), port), dst: netip.MustParseAddrPort("192.0.2.1:443"), protocol: 17,
			payload: encryptTestInitial(quicV1, testClientHello([]byte(host), []string{"h3"}, false))}
	}
	blocked := f.inspect(makePacket("blocked.test", 12345))
	assert.Equal(t, verdictDrop, blocked.verdict)
	assert.Zero(t, blocked.toClient)
	allowed := f.inspect(makePacket("ordinary.test", 12346))
	assert.Equal(t, verdictAccept, allowed.verdict)
	assert.Zero(t, allowed.toClient)
}

func TestInspectQUICOutsideConfiguredPortsPassesWithoutInspection(t *testing.T) {
	t.Parallel()

	filter, err := filtering.New(&filtering.Config{
		Logger:            slogutil.NewDiscardLogger(),
		ProtectionEnabled: true,
	}, []filtering.Filter{{ID: 1, Data: []byte("||blocked.test^")}})
	require.NoError(t, err)
	filter.SetEnabled(true)

	f, err := New(&Config{
		Logger: slogutil.NewDiscardLogger(),
		Filter: filter,
		Params: Params{
			Ports:       []uint16{443},
			InspectQUIC: true,
			QUICPorts:   []uint16{853},
		},
	})
	require.NoError(t, err)
	p := &packet{
		src:      netip.MustParseAddrPort("127.0.0.1:12345"),
		dst:      netip.MustParseAddrPort("192.0.2.1:443"),
		protocol: 17,
		payload:  encryptTestInitial(quicV1, testClientHello([]byte("blocked.test"), []string{"h3"}, false)),
	}

	res := f.inspect(p)
	assert.Equal(t, verdictAccept, res.verdict)
	assert.Empty(t, f.flows, "unconfigured UDP destinations must not create flow state or be inspected")
}

func encryptTestInitial(version uint32, hello []byte) []byte {
	dcid := []byte{0x83, 0x94, 0xc8, 0xf0, 0x3e, 0x51, 0x57, 0x08}
	frame := []byte{6, 0}
	frame = appendQUICTestVarint(frame, uint64(len(hello)))
	frame = append(frame, hello...)
	frame = append(frame, make([]byte, 1200)...)
	plain := frame
	length := len(plain) + 17 // one packet number octet and GCM tag
	first := byte(0xc0)
	if version == quicV2 {
		first = 0xd0
	}
	header := []byte{first}
	header = binary.BigEndian.AppendUint32(header, version)
	header = append(header, byte(len(dcid)))
	header = append(header, dcid...)
	header = append(header, 0) // empty SCID
	header = append(header, 0) // empty token
	header = appendQUICTestVarint(header, uint64(length))
	pnOffset := len(header)
	header = append(header, 0) // packet number zero
	key, iv, hp, _ := quicClientKeys(version, dcid)
	block, _ := aes.NewCipher(key)
	aead, _ := cipher.NewGCM(block)
	ciphertext := aead.Seal(nil, iv, plain, header)
	pkt := append(header, ciphertext...)
	hpBlock, _ := aes.NewCipher(hp)
	var mask [16]byte
	hpBlock.Encrypt(mask[:], pkt[pnOffset+4:pnOffset+20])
	pkt[0] ^= mask[0] & 0x0f
	pkt[pnOffset] ^= mask[1]
	return pkt
}

func appendQUICTestVarint(b []byte, v uint64) []byte {
	switch {
	case v < 64:
		return append(b, byte(v))
	case v < 16384:
		return append(b, byte(v>>8)|0x40, byte(v))
	default:
		panic("test fixture length too large")
	}
}
