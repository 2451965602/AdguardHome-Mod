// These compact encrypted Initial fixtures are constructed from the QUIC
// Initial key schedule in RFC 9001 Appendix A (v1) and RFC 9369 Appendix A
// (v2), using the RFC salts and a test ClientHello.
func TestDecryptQUICInitialVersions(t *testing.T) {
	t.Parallel()
	for _, version := range []uint32{quicV1, quicV2} {
		t.Run(map[uint32]string{quicV1: "v1", quicV2: "v2"}[version], func(t *testing.T) {
			t.Parallel()
			hello := testClientHello([]byte("blocked.test"), []string{"h3"}, false)
			info, err := decryptQUICInitial(encryptTestInitial(version, hello))
			require.NoError(t, err)
			assert.Equal(t, "blocked.test", info.serverName)
			assert.Equal(t, []string{"h3"}, info.alpn)
		})
	}
}

